import { strict as assert } from 'node:assert';
import { suggestFocusInterval, validateFocusAllocations } from '../src/features/focus/focus-personalization';
import type { FocusOutcome } from '../src/data/schema';
import { createFocusSession, extendFocusTimer, pauseFocusTimer, timerRemainingMs, configureBreakReminders, breakReminderDue, acknowledgeBreakReminder, resumeFocusTimer, suggestBreak } from '../src/features/focus/focus-engine';
import { validateFocusSession } from '../src/features/focus/focus-storage';
import { createEmptyWorkspace } from '../src/data/schema';
import { migrateAndValidateWorkspace } from '../src/data/migrations';
import { recordFocusOutcome } from '../src/features/adaptive/outcome-engine';
import { computeCompletedFocusMinutesToday } from '../src/features/today/today-progress';
import { buildProgressSnapshot, buildTopicTrends } from '../src/features/progress/progress-engine';
import { createStudyTask } from '../src/features/planning/task-engine';
import { localDayKey } from '../src/features/planning/day-engine';
const now = 1_800_000_000_000;
const make = (minutes: number, status: FocusOutcome['status'] = 'finished', endedAt = now): FocusOutcome => ({ id: String(minutes) + status, startedAt: now - 600_000, endedAt: status === 'started' ? 0 : endedAt, status, plannedMinutes: 25, minutes, launchMode: 'full', taskOnly: true, overdue: false });
assert.equal(suggestFocusInterval([make(0), make(1), make(3), make(30, 'started'), make(50, 'abandoned')], now), null);
assert.deepEqual(suggestFocusInterval([make(25), make(35), make(45), make(0)], now), { minutes: 35, samples: 3 });
assert.equal(suggestFocusInterval([make(25), make(30), make(60, 'finished', now - 31 * 86400000)], now), null);
assert.equal(validateFocusAllocations([{ subject: 'Maths', minutes: 12 }, { subject: 'Biology', minutes: 8 }], 20), null);
assert.ok(validateFocusAllocations([{ subject: 'Maths', minutes: 21 }], 20));
assert.ok(validateFocusAllocations([{ subject: '', minutes: 5 }], 20));
assert.ok(validateFocusAllocations([{ subject: 'Maths', minutes: 0.5 }], 20));
const free = createFocusSession({ freeFocus: true, topicName: 'Free focus', subject: 'Unassigned', plannedMinutes: 25, breakMinutes: 5, launchMode: 'full', timerMode: 'stopwatch', tinyStep: '', now });
assert.equal(validateFocusSession(free).freeFocus, true);
assert.throws(() => validateFocusSession({ ...free, freeFocus: false }));
const reminder = configureBreakReminders(free, 25, 2, now);
assert.equal(breakReminderDue(reminder, now + 24 * 60_000), false);
assert.equal(breakReminderDue(reminder, now + 25 * 60_000), true);
const rest = acknowledgeBreakReminder(reminder, true, now + 25 * 60_000);
assert.equal(rest.runningSince, null);
assert.equal(rest.breakReminder?.remaining, 1);
assert.equal(breakReminderDue(rest, now + 60 * 60_000), false);
const resumed = resumeFocusTimer(rest, now + 60 * 60_000);
assert.equal(breakReminderDue(resumed, now + 85 * 60_000), true);
assert.equal(validateFocusSession(rest).breakReminder?.remaining, 1);
assert.equal(validateFocusSession(suggestBreak(rest, 25, now + 85 * 60_000)).breakReminder, undefined);
const planned = createFocusSession({ taskId: 'task', topicName: 'Math', subject: 'Maths', plannedMinutes: 25, breakMinutes: 5, launchMode: 'full', timerMode: 'pomodoro', breaksRemaining: 3, tinyStep: '', now });
assert.equal(validateFocusSession(planned).breaksRemaining, 3);
assert.throws(() => validateFocusSession({ ...planned, breaksRemaining: 9 }));
const longer = extendFocusTimer(planned, 5, now + 25 * 60_000);
assert.equal(longer.plannedFocusMinutes, 30);
assert.equal(timerRemainingMs(longer, now + 25 * 60_000), 5 * 60_000);
const pausedLonger = extendFocusTimer(pauseFocusTimer(planned, now + 10 * 60_000), 5, now + 12 * 60_000);
assert.equal(pausedLonger.runningSince, null);
assert.equal(pausedLonger.plannedFocusMinutes, 30);
const workspace = createEmptyWorkspace(now);
recordFocusOutcome(workspace, free, 'finished', 20, now + 20 * 60_000);
workspace.focusOutcomes![0]!.allocations = [{ subject: 'Maths', minutes: 12 }, { subject: 'Biology', minutes: 8 }];
const restored = migrateAndValidateWorkspace(workspace);
assert.deepEqual(restored.focusOutcomes![0]!.allocations?.map(a => a.minutes), [12, 8]);
assert.equal(computeCompletedFocusMinutesToday(restored, now + 21 * 60_000), 20);
assert.equal(buildProgressSnapshot(restored, now + 21 * 60_000).study.todayMinutes, 20);
restored.topics.push({ id: 'math', name: 'Equations', subject: 'Maths', createdAt: now, status: 'learning', priority: 2, estimate: 25, notes: '', dueAt: 0, intervalDays: 0, lastGrade: 0, lastReviewed: 0, snoozeUntil: 0, cards: [] });
restored.focusOutcomes![0]!.allocations![0] = { subject: 'Maths', minutes: 12, topicId: 'math', topicName: 'Equations' };
assert.equal(buildTopicTrends(restored, now + 21 * 60_000)[0]?.recentMinutes, 12);
const task = createStudyTask({ title: 'Biology', planState: 'today', now });
task.focusDayKey = localDayKey(now);
task.focusMinutesForDay = 10;
const taskSession = createFocusSession({ taskId: task.id, topicName: 'Biology', subject: 'Biology', plannedMinutes: 10, breakMinutes: 5, launchMode: 'full', timerMode: 'countdown', tinyStep: '', now: now + 20 * 60_000 });
task.lastFocusSessionId = taskSession.id;
restored.tasks.push(task);
recordFocusOutcome(restored, taskSession, 'finished', 10, now + 30 * 60_000);
assert.equal(computeCompletedFocusMinutesToday(restored, now + 31 * 60_000), 30);
assert.equal(buildProgressSnapshot(restored, now + 31 * 60_000).study.todayMinutes, 30);
assert.throws(() => migrateAndValidateWorkspace({ ...workspace, focusOutcomes: [{ ...workspace.focusOutcomes![0], allocations: [{ subject: 'Maths', minutes: 21 }] }] }));
console.log('Habit evidence and focus allocation checks passed');
