import type { WorkspaceState } from '@/src/data/schema';
import type { AssistantActionBatch, AssistantExamRef, AssistantTopicRef } from './ai-action-engine';
import type { AssistantClarificationAnswers } from './assistant-clarification';
import { normalizeSchoolworkLanguage, validSchoolworkDate } from './schoolwork-language';

export type GroundingQuestion = {
  reason: 'missing-date' | 'missing-target' | 'ambiguous-reference';
  question: string;
  missingFields: string[];
};
type Input = {
  workspace: WorkspaceState;
  userRequest: string;
  currentDate: string;
  clarificationAnswers?: AssistantClarificationAnswers;
};
const dateQuestion = (): GroundingQuestion => ({ reason: 'missing-date',
  question: 'What exact day is the exam? Reply with YYYY-MM-DD, today or tomorrow.', missingFields: ['dueDate'] });
const targetQuestion = (kind: 'topic' | 'exam', ambiguous = false): GroundingQuestion => ({
  reason: ambiguous ? 'ambiguous-reference' : 'missing-target',
  question: `Which existing ${kind} do you mean? ${kind === 'topic' ? 'Reply with its exact name.' : 'Include its exact name in the request.'}`,
  missingFields: [kind],
});
export class AssistantGroundingError extends Error {
  constructor(public readonly clarification: GroundingQuestion) {
    super(clarification.question);
    this.name = 'AssistantGroundingError';
  }
}

// Deliberately narrow date evidence. Unrecognized dates ask instead of accepting
// a plausible date generated by a model. Answers are trusted explicit UI slots.
function dateEvidence(input: Input): string | null {
  const answer = input.clarificationAnswers?.dueDate;
  if (answer != null) return validSchoolworkDate(answer) ? answer : null;
  const text = normalizeSchoolworkLanguage(input.userRequest);
  if (/\b(?:next week|next month|monday|tuesday|wednesday|thursday|friday|saturday|sunday|yesterday|later|not sure|unknown|don't know|do not know|baad mein)\b/.test(text)) return null;
  const dates: string[] = [];
  for (const match of text.matchAll(/\b(?:20\d{2}-\d{2}-\d{2}|day after tomorrow|tomorrow|today|tonight|in \d+ days?)\b/g)) {
    const value = match[0];
    if (/^20\d{2}-/.test(value)) {
      if (!validSchoolworkDate(value)) return null;
      dates.push(value);
    } else {
      if (!validSchoolworkDate(input.currentDate)) return null;
      const days = value.startsWith('in ') ? Number(value.split(' ')[1]) : value === 'day after tomorrow' ? 2 : value === 'tomorrow' ? 1 : 0;
      if (!Number.isInteger(days) || days < 0 || days > 30) return null;
      const base = new Date(`${input.currentDate}T12:00:00Z`);
      base.setUTCDate(base.getUTCDate() + days);
      dates.push(base.toISOString().slice(0, 10));
    }
  }
  return dates.length && new Set(dates).size === 1 ? dates[0]! : null;
}

export function checkAssistantRequestGrounding(input: Input): GroundingQuestion | null {
  const answers = input.clarificationAnswers;
  if (answers?.topicId && !input.workspace.topics.some(t => t.id === answers.topicId)) return targetQuestion('topic');
  if (answers?.dueDate != null && !validSchoolworkDate(answers.dueDate)) return dateQuestion();
  const text = normalizeSchoolworkLanguage(input.userRequest);
  if (/^(?:please\s+)?(?:add|create|record|schedule)\b.{0,70}\b(?:exam|quiz|test|assessment|viva)\b/.test(text) &&
      !/\b(?:exam|quiz|test|assessment)\s+plan\b|\b(?:don't|do not|already|completed|if|maybe)\b/.test(text) && !dateEvidence(input)) return dateQuestion();
  if (/^(?:please\s+)?(?:make|set|mark|update|raise|lower|increase|decrease)\s+(?:it|this|that|the selected (?:topic|chapter))\b/.test(text) &&
      !input.clarificationAnswers?.topicId) return targetQuestion('topic');
  return null;
}

const key = (value: string) => value.normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
const GENERIC_WORDS = new Set(['add', 'create', 'record', 'schedule', 'update', 'make', 'set', 'mark', 'raise', 'lower', 'increase', 'decrease', 'priority', 'review', 'practice', 'study', 'chapter', 'topic', 'subject', 'exam', 'today', 'tomorrow', 'current', 'selected', 'please', 'the', 'this', 'that', 'from', 'with', 'about']);
function mentions(text: string, name: string) {
  const request = ` ${key(text)} `;
  const target = key(name);
  if (!target) return false;
  if (target.split(' ').every(word => GENERIC_WORDS.has(word))) {
    return [...text.matchAll(/["“]([^"”]+)["”]/g)].some(match => key(match[1]!) === target);
  }
  if (request.includes(` ${target} `)) return true;
  // A unique prefix such as "trig" is allowed; arbitrary substring/fuzzy ID
  // matching is not. The caller checks uniqueness against the entire workspace.
  const words = target.split(' ');
  return key(text).split(' ').some(word => word.length >= 4 && !GENERIC_WORDS.has(word) && words.some(candidate => candidate.startsWith(word)));
}
function explicitlyNamesId(text: string, id: string) {
  return [...text.matchAll(/\bid\s+(?:"([^"]+)"|'([^']+)'|([^\s,;!?]+))/gi)]
    .some(match => (match[1] ?? match[2] ?? match[3]) === id);
}

export function checkAssistantActionGrounding(input: Input, batch: AssistantActionBatch): GroundingQuestion | null {
  const createdTopics = new Set<string>();
  const createdExams = new Set<string>();
  const examActions = batch.actions.filter(action => action.type === 'create_exam');
  if (examActions.length) {
    // A single clarification date cannot assign separate dates to multiple exams.
    if (examActions.length > 1) return { reason: 'ambiguous-reference', question: 'Please create one exam at a time so each date is explicit.', missingFields: ['request'] };
    const date = dateEvidence(input);
    if (!date || examActions[0]!.date !== date) return dateQuestion();
  }
  const topic = (ref: AssistantTopicRef): GroundingQuestion | null => {
    if ('clientRef' in ref) return createdTopics.has(ref.clientRef) ? null : targetQuestion('topic');
    const matches = 'topicId' in ref ? input.workspace.topics.filter(t => t.id === ref.topicId)
      : input.workspace.topics.filter(t => key(t.name) === key(ref.name) && key(t.subject) === key(ref.subject));
    if (matches.length !== 1) return targetQuestion('topic', matches.length > 1);
    const selected = matches[0]!;
    if (input.clarificationAnswers?.topicId === selected.id || explicitlyNamesId(input.userRequest, selected.id)) return null;
    const named = input.workspace.topics.filter(t => mentions(input.userRequest, t.name));
    if (!named.some(t => t.id === selected.id)) return targetQuestion('topic');
    const duplicates = named.filter(t => key(t.name) === key(selected.name));
    if (duplicates.length > 1 && (!mentions(input.userRequest, selected.subject) ||
        duplicates.filter(t => key(t.subject) === key(selected.subject)).length !== 1)) return targetQuestion('topic', true);
    // Prefixes which could identify multiple names must not let the model choose.
    if (!` ${key(input.userRequest)} `.includes(` ${key(selected.name)} `) && named.length !== 1) return targetQuestion('topic', true);
    return null;
  };
  const exam = (ref: AssistantExamRef): GroundingQuestion | null => {
    if ('clientRef' in ref) return createdExams.has(ref.clientRef) ? null : targetQuestion('exam');
    const matches = 'examId' in ref ? input.workspace.exams.filter(e => e.id === ref.examId)
      : input.workspace.exams.filter(e => key(e.name) === key(ref.name));
    if (matches.length !== 1) return targetQuestion('exam', matches.length > 1);
    const selected = matches[0]!;
    if (explicitlyNamesId(input.userRequest, selected.id)) return null;
    const named = input.workspace.exams.filter(e => ` ${key(input.userRequest)} `.includes(` ${key(e.name)} `));
    if (named.filter(e => key(e.name) === key(selected.name)).length === 1) return null;
    if (!named.length && /\b(?:all|upcoming)\s+(?:my\s+)?exams\b/i.test(input.userRequest)) return null;
    return targetQuestion('exam', named.length > 1);
  };
  for (const action of batch.actions) {
    let question: GroundingQuestion | null = null;
    if (action.type === 'update_topic') question = topic(action.topic);
    if (action.type === 'create_exam') for (const ref of action.topicRefs) { question = topic(ref); if (question) break; }
    if (action.type === 'create_task') question = (action.topic ? topic(action.topic) : null) ?? (action.exam ? exam(action.exam) : null);
    if (action.type === 'generate_exam_plan') {
      for (const ref of action.examRefs ?? []) { question = exam(ref); if (question) break; }
      if (!question) for (const override of action.topicOverrides) { question = topic(override.topic); if (question) break; }
    }
    if (question) return question; // Reject the entire proposed batch, never apply a subset.
    if (action.type === 'create_topic' && action.clientRef) createdTopics.add(action.clientRef);
    if (action.type === 'create_exam' && action.clientRef) createdExams.add(action.clientRef);
  }
  return null;
}
